"""
Natural Language Query Engine Models.

Defines schemas for the Natural Language to Cypher mapping interface:
- NaturalLanguageQueryRequest: User's plain English query string.
- NaturalLanguageQueryResponse: Parsed constraints, generated Cypher statement,
  execution results, and academic explanation of the graph traversal logic.
"""

from typing import Any, Dict, List, Optional
from pydantic import BaseModel, Field
from app.models.animal import AnimalSummary


class NaturalLanguageQueryRequest(BaseModel):
    """
    Input payload for the Natural Language Cypher Query interface.
    """
    question: str = Field(..., description="Plain-English question (e.g. 'Show endangered animals that live in forests')")


class NaturalLanguageQueryResponse(BaseModel):
    """
    Output payload containing entity extraction details, generated Cypher, and query results.
    """
    question: str = Field(..., description="Original question submitted by user")
    detectedFilters: Dict[str, Any] = Field(
        default_factory=dict,
        description="Extracted filter entities mapped from vocabulary (e.g. {'status': 'Endangered', 'habitat': 'Forest'})"
    )
    cypherQuery: str = Field(..., description="The executable Cypher query generated by the backend translation engine")
    results: List[AnimalSummary] = Field(default_factory=list, description="List of matching Animal entities")
    resultCount: int = Field(..., description="Total count of matched entities")
    explanation: Optional[str] = Field(None, description="Human-readable explanation of how the query was constructed")
